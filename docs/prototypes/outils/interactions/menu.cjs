// Steps through the phone menu's entrance and exit with a stub runtime.
const fs = require('fs');
const html = fs.readFileSync(process.argv[2], 'utf8');
const script = html.match(/<script type="text\/x-dc"[^>]*>([\s\S]*?)<\/script>/)[1];
let raf = [];
let timers = [];
global.window = { matchMedia: () => ({ matches: process.argv[3] === 'reduce' }) };
global.requestAnimationFrame = (f) => { raf.push(f); return raf.length; };
global.cancelAnimationFrame = () => {};
global.performance = { now: () => 0 };
global.setTimeout = (f, ms) => { const t = { f, ms, on: true }; timers.push(t); return t; };
global.clearTimeout = (t) => { if (t) t.on = false; };
class DCLogic { constructor(p) { this.props = p || {}; this.state = {}; } setState(s) { Object.assign(this.state, typeof s === 'function' ? s(this.state) : s); } }
const Component = new Function('DCLogic', script + '\nreturn Component;')(DCLogic);
const flush = () => { const q = raf; raf = []; q.forEach((f) => f(16)); };
const fire = (ms) => { const due = timers.filter((t) => t.on && t.ms === ms); timers = timers.filter((t) => !due.includes(t)); due.forEach((t) => t.f()); };
let failed = 0;
const check = (label, ok, extra) => { console.log((ok ? 'ok  ' : 'FAIL') + ' ' + label + (extra ? ' ' + JSON.stringify(extra) : '')); if (!ok) failed++; };
const c = new Component({});
c.componentDidMount = c.componentDidMount.bind(c);
c.scroller = { scrollTop: 0 };
c.componentDidMount();
let v = c.renderVals();
check('closed at first', !v.menuOpen && v.menuOp === 0);
v.openMenu();
v = c.renderVals();
check('mounted, still dark and transparent', v.menuOpen && v.menuOp === 0 && v.menuItemOp === 0 && v.menuItemY === (process.argv[3] === 'reduce' ? 0 : 10));
flush(); flush();
v = c.renderVals();
check('two frames later it comes in', v.menuOp === 1 && v.menuItemOp === 1 && v.menuItemY === 0 && /260ms/.test(v.menuFade) && /100ms/.test(v.menuItem2));
v.closeMenu();
v = c.renderVals();
check('Fermer: fades out fast, words stay, no clicks', v.menuOpen && v.menuOp === 0 && v.menuItemOp === 1 && v.menuPE === 'none' && /180ms/.test(v.menuFade));
v.openMenu();
v = c.renderVals();
check('reopened while closing: back in at once', v.menuOp === 1 && c.state.menuOut === false);
fire(200);
check('the pending unmount was cancelled', c.state.menuOpen === true);
v.closeMenu();
fire(200);
v = c.renderVals();
check('unmounted 0.2 s after Fermer', !v.menuOpen && !c.state.menuOut);
v.openMenu(); flush(); flush();
c.land(1);
v = c.renderVals();
check('a menu link closes it in the dark at once', !v.menuOpen && !c.state.menuIn && !c.state.menuOut);
console.log(failed ? failed + ' failed' : 'all good');
